-- ============================================================================
-- Package: DECISION_PKG (DecisionDB.runRiskAssessment stored procedure)
-- ============================================================================
CREATE OR REPLACE PACKAGE DECISION_PKG AS
    -- Run automated risk assessment
    -- Called by: DecisionDB.jca - operation="runRiskAssessment"
    -- InteractionSpec: oracle.tip.adapter.db.DBStoredProcedureInteractionSpec
    PROCEDURE RUN_RISK_ASSESSMENT(
        p_loan_id        IN  VARCHAR2,
        p_credit_score   IN  NUMBER,
        p_ltv_ratio      IN  NUMBER,
        p_monthly_income IN  NUMBER,
        p_loan_amount    IN  NUMBER,
        p_risk_score     OUT NUMBER,
        p_recommendation OUT VARCHAR2,
        p_notes          OUT VARCHAR2
    );
END DECISION_PKG;
/

CREATE OR REPLACE PACKAGE BODY DECISION_PKG AS
    PROCEDURE RUN_RISK_ASSESSMENT(
        p_loan_id        IN  VARCHAR2,
        p_credit_score   IN  NUMBER,
        p_ltv_ratio      IN  NUMBER,
        p_monthly_income IN  NUMBER,
        p_loan_amount    IN  NUMBER,
        p_risk_score     OUT NUMBER,
        p_recommendation OUT VARCHAR2,
        p_notes          OUT VARCHAR2
    ) IS
        v_dti_ratio NUMBER;
        v_score NUMBER := 0;
    BEGIN
        -- Calculate DTI (assuming monthly loan payment is ~0.6% of loan amount)
        v_dti_ratio := ((p_loan_amount * 0.006) / p_monthly_income) * 100;

        -- Score calculation based on credit score (0-400 points)
        IF p_credit_score >= 750 THEN
            v_score := v_score + 400;
        ELSIF p_credit_score >= 700 THEN
            v_score := v_score + 300;
        ELSIF p_credit_score >= 650 THEN
            v_score := v_score + 200;
        ELSIF p_credit_score >= 600 THEN
            v_score := v_score + 100;
        END IF;

        -- Score based on LTV (0-300 points)
        IF p_ltv_ratio <= 80 THEN
            v_score := v_score + 300;
        ELSIF p_ltv_ratio <= 90 THEN
            v_score := v_score + 200;
        ELSIF p_ltv_ratio <= 95 THEN
            v_score := v_score + 100;
        END IF;

        -- Score based on DTI (0-300 points)
        IF v_dti_ratio <= 28 THEN
            v_score := v_score + 300;
        ELSIF v_dti_ratio <= 36 THEN
            v_score := v_score + 200;
        ELSIF v_dti_ratio <= 43 THEN
            v_score := v_score + 100;
        END IF;

        p_risk_score := v_score;

        -- Generate recommendation
        IF v_score >= 800 THEN
            p_recommendation := 'APPROVED';
            p_notes := 'Excellent risk profile. Auto-approved.';
        ELSIF v_score >= 600 THEN
            p_recommendation := 'APPROVED';
            p_notes := 'Good risk profile. Approved with standard terms.';
        ELSIF v_score >= 400 THEN
            p_recommendation := 'MANUAL_REVIEW';
            p_notes := 'Moderate risk. Requires manual underwriting review.';
        ELSE
            p_recommendation := 'REJECTED';
            p_notes := 'High risk profile. Does not meet minimum requirements.';
        END IF;

    END RUN_RISK_ASSESSMENT;
END DECISION_PKG;
/

