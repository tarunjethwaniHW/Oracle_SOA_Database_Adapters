-- ============================================================================
-- Table: BORROWERS (BorrowerDB.Borrower)
-- ============================================================================
CREATE TABLE BORROWERS (
    BORROWER_ID         NUMBER(19) PRIMARY KEY,
    SSN                 VARCHAR2(11) NOT NULL UNIQUE,
    NAME                VARCHAR2(200) NOT NULL,
    CREDIT_SCORE        NUMBER(3),
    MONTHLY_INCOME      NUMBER(15,2) NOT NULL,
    CREATED_AT          TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT          TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE SEQUENCE BORROWER_SEQ START WITH 1 INCREMENT BY 1;

CREATE INDEX IDX_BORROWERS_SSN ON BORROWERS(SSN);

COMMENT ON TABLE BORROWERS IS 'Borrower information - linked via BorrowerDB.jca adapter';
COMMENT ON COLUMN BORROWERS.BORROWER_ID IS 'Primary key - populated from BORROWER_SEQ';
COMMENT ON COLUMN BORROWERS.SSN IS 'Social Security Number - used for selectBorrowerBySSN operation';
COMMENT ON COLUMN BORROWERS.CREDIT_SCORE IS 'Credit score (300-850) - updated via updateBorrowerCredit operation';

-- ============================================================================
-- Table: LOAN_APPLICATIONS (LoanDB.LoanApplication)
-- ============================================================================
CREATE TABLE LOAN_APPLICATIONS (
    LOAN_ID             VARCHAR2(50) PRIMARY KEY,
    BORROWER_ID         NUMBER(19) NOT NULL REFERENCES BORROWERS(BORROWER_ID),
    LOAN_AMOUNT         NUMBER(15,2) NOT NULL,
    PROPERTY_VALUE      NUMBER(15,2) NOT NULL,
    PROPERTY_ADDRESS    VARCHAR2(500),
    LTV_RATIO           NUMBER(5,2),
    STATUS              VARCHAR2(50) DEFAULT 'PENDING',
    CREATED_AT          TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT          TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IDX_LOANS_BORROWER ON LOAN_APPLICATIONS(BORROWER_ID);
CREATE INDEX IDX_LOANS_STATUS ON LOAN_APPLICATIONS(STATUS);

COMMENT ON TABLE LOAN_APPLICATIONS IS 'Loan application records - linked via LoanDB.jca adapter';
COMMENT ON COLUMN LOAN_APPLICATIONS.LOAN_ID IS 'Primary key - UUID generated by BPEL process';
COMMENT ON COLUMN LOAN_APPLICATIONS.LTV_RATIO IS 'Loan-to-Value ratio - calculated by LOAN_PKG.CALCULATE_LTV';
COMMENT ON COLUMN LOAN_APPLICATIONS.STATUS IS 'Application status: PENDING, APPROVED, REJECTED, MANUAL_REVIEW';

-- ============================================================================
-- Table: LOAN_DECISIONS (DecisionDB.LoanDecision)
-- ============================================================================
CREATE TABLE LOAN_DECISIONS (
    DECISION_ID         VARCHAR2(50) PRIMARY KEY,
    LOAN_ID             VARCHAR2(50) NOT NULL REFERENCES LOAN_APPLICATIONS(LOAN_ID),
    DECISION            VARCHAR2(50) NOT NULL,
    RISK_SCORE          NUMBER(4),
    NOTES               VARCHAR2(2000),
    REVIEWED_BY         VARCHAR2(100),
    CREATED_AT          TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IDX_DECISIONS_LOAN ON LOAN_DECISIONS(LOAN_ID);
CREATE INDEX IDX_DECISIONS_DECISION ON LOAN_DECISIONS(DECISION);

COMMENT ON TABLE LOAN_DECISIONS IS 'Loan decision audit trail - linked via DecisionDB.jca adapter';
COMMENT ON COLUMN LOAN_DECISIONS.DECISION IS 'Decision result: APPROVED, REJECTED, MANUAL_REVIEW';
COMMENT ON COLUMN LOAN_DECISIONS.RISK_SCORE IS 'Risk score (0-1000) - calculated by DECISION_PKG.RUN_RISK_ASSESSMENT';
COMMENT ON COLUMN LOAN_DECISIONS.REVIEWED_BY IS 'Reviewer ID for manual decisions';

-- ============================================================================
-- Package: LOAN_PKG (LoanDB.calculateLTV stored procedure)
-- ============================================================================
CREATE OR REPLACE PACKAGE LOAN_PKG AS
    -- Calculate Loan-to-Value ratio
    -- Called by: LoanDB.jca - operation="calculateLTV"
    -- InteractionSpec: oracle.tip.adapter.db.DBStoredProcedureInteractionSpec
    PROCEDURE CALCULATE_LTV(
        p_loan_amount    IN  NUMBER,
        p_property_value IN  NUMBER,
        p_ltv_ratio      OUT NUMBER
    );
END LOAN_PKG;
/

CREATE OR REPLACE PACKAGE BODY LOAN_PKG AS
    PROCEDURE CALCULATE_LTV(
        p_loan_amount    IN  NUMBER,
        p_property_value IN  NUMBER,
        p_ltv_ratio      OUT NUMBER
    ) IS
    BEGIN
        IF p_property_value > 0 THEN
            p_ltv_ratio := ROUND((p_loan_amount / p_property_value) * 100, 2);
        ELSE
            p_ltv_ratio := 0;
        END IF;
    END CALCULATE_LTV;
END LOAN_PKG;
/

